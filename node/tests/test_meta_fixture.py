"""The cross-language fixture, checked from the Python side.

tests/fixtures/meta-batch-fixture.json (repo root) is generated by
THIS library (node/tests/gen_meta_batch_fixture.py) and consumed by
the TypeScript ingest's tests. The fixture file itself lands with
the ingest PR, so this test SKIPS while that PR is unmerged; once
both are on dev it is a hard check: if it fails, claims.py has
drifted from the committed fixture — regenerate it and commit both
together, or the TS suite is pinning a contract Python no longer
speaks.
"""
import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from metasync_node.meta import claims as C

FIXTURE = Path(__file__).resolve().parents[2] / "tests" / "fixtures" \
    / "meta-batch-fixture.json"


@unittest.skipUnless(FIXTURE.exists(),
                     "fixture lands with the claims ingest PR")
class FixtureTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fx = json.loads(FIXTURE.read_text(encoding="utf-8"))

    def test_envelope_verifies_and_digest_matches(self):
        batch = C.verify_batch(self.fx["public_key_b64"], self.fx["envelope"])
        self.assertEqual(C.batch_digest(batch), self.fx["expected_digest"])

    def test_contract_lists_match_this_library(self):
        contract = self.fx["contract"]
        self.assertEqual(contract["kinds"], sorted(C.KINDS))
        self.assertEqual(contract["fields"], sorted(C.ALL_FIELDS))
        self.assertEqual(contract["sources"], sorted(C.SOURCES))
        self.assertEqual(contract["reserved_sources"],
                         sorted(C.RESERVED_SOURCES))

    def test_nul_in_object_key_refused(self):
        # Keys are canonical-form strings too: a wire batch carrying a
        # NUL key must fail the digest computation, not sign cleanly
        # here and then be refused by the TS ingest.
        with self.assertRaises(C.ClaimError):
            C.canonical_bytes({"a\x00b": 1})
        with self.assertRaises(C.ClaimError):
            C.canonical_bytes({"a\ud800b": 1})


if __name__ == "__main__":
    unittest.main()
