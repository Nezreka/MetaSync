"""Regenerate tests/fixtures/meta-batch-fixture.json (repo root).

The fixture is the cross-language pin between this claims library
and the TypeScript ingest in src/metasync/: it is generated HERE, by
the Python implementation, with a fixed test-only key, and both
test suites verify against it (node/tests/test_meta_fixture.py and
tests/metasync-claims.test.ts). If claims.py changes shape, rerun:

    python3 node/tests/gen_meta_batch_fixture.py

and commit the regenerated fixture with the change. (The fixture
file itself lands with the ingest PR; this generator is committed
here so the recipe is never just a chat transcript.)
"""
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
)

from metasync_node.meta import claims, soulid

OUT = Path(__file__).resolve().parents[2] / "tests" / "fixtures" \
    / "meta-batch-fixture.json"


def main() -> None:
    seed = bytes(range(1, 33))
    priv = Ed25519PrivateKey.from_private_bytes(seed)
    pub_raw = priv.public_key().public_bytes_raw()
    pub_b64 = claims.b64url_encode(pub_raw)
    artist = soulid.generate_soul_id("artist", "周杰倫")
    track = soulid.generate_soul_id("track", "Radiohead", "Karma Police")
    batch_claims = [
        {"subject": artist, "kind": "artist", "field": "name",
         "value": ["周杰倫"], "source": "musicbrainz",
         "soulid_version": "kinded_v2"},
        {"subject": artist, "kind": "artist", "field": "artist_mbid",
         "value": "b7f2c1d4-0000-4000-8000-000000000000",
         "source": "musicbrainz", "soulid_version": "kinded_v2"},
        {"subject": track, "kind": "track", "field": "name",
         "value": ["Radiohead", "Karma Police"], "source": "deezer",
         "soulid_version": "kinded_v2"},
        {"subject": track, "kind": "track", "field": "duration_ms",
         "value": 284000, "source": "file_tags",
         "soulid_version": "kinded_v2"},
        {"subject": track, "kind": "track", "field": "genres",
         "value": "alternative rock", "source": "deezer",
         "soulid_version": "kinded_v2"},
        {"subject": track, "kind": "track", "field": "hydrabase_id",
         "value": "hb_0123456789", "source": "hydrabase",
         "soulid_version": "kinded_v2"},
    ]
    retraction = {"subject": track, "kind": "track", "field": "isrc",
                  "value": "GBAYE9700182", "source": "deezer",
                  "soulid_version": "kinded_v2"}
    batch = claims.make_batch(pub_b64, batch_claims,
                              retractions=[retraction],
                              nonce="fixture-nonce-0001",
                              asserted_at=1_700_000_000)
    fixture = {
        "note": "Generated by the Python shared library "
                "(node/metasync_node/meta/claims.py, PR #10) with a "
                "FIXED test-only key. The TypeScript ingest must "
                "verify this envelope, reproduce this digest exactly, "
                "and agree with the contract lists below, or the two "
                "implementations have diverged. Test-only seed — never "
                "a real node key.",
        "seed_hex": seed.hex(),
        "public_key_b64": pub_b64,
        "node_id": hashlib.sha256(pub_raw).hexdigest(),
        "envelope": claims.sign_batch(priv, batch),
        "expected_digest": claims.batch_digest(batch),
        "contract": {
            "kinds": sorted(claims.KINDS),
            "fields": sorted(claims.ALL_FIELDS),
            "sources": sorted(claims.SOURCES),
            "reserved_sources": sorted(claims.RESERVED_SOURCES),
        },
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, ensure_ascii=False, indent=1) + "\n")
    print(f"wrote {OUT} digest {fixture['expected_digest'][:16]}")


if __name__ == "__main__":
    main()
